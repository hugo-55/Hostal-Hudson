const LangCtx = createContext({ lang: 'es', setLang: () => {}, t: dict.es });

export function LangProvider({ children }) {
  const [lang, setLang] = useState('es');
  useEffect(() => {
    try {
      const saved = localStorage.getItem('hostal-lang');
      if (saved === 'en' || saved === 'es') setLang(saved);
    } catch {}
  }, []);
  useEffect(() => {
    try { localStorage.setItem('hostal-lang', lang); } catch {}
    document.documentElement.lang = lang === 'es' ? 'es-CL' : 'en';
  }, [lang ]);
  return <LangCtx.Provider value={{ lang, setLang, t: dict[lang] }}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);
